/**
 * The Guide's icon (the old OS's helper): a floppy disk with a face. Only the
 * 16 px copy is still written (system/usr/share/icons/guide-16.png).
 */
function floppy(): Img {
  const img = layer();
  const [bx, by, bw, bh] = [6, 4, 20, 23];
  const body = layer().rect(bx, by, bw, bh, 13);
  // cut corner, shading
  body
    .set(bx + bw - 1, by, ".")
    .set(bx + bw - 2, by, ".")
    .set(bx + bw - 1, by + 1, ".");
  body
    .rect(bx + bw - 1, by + 3, 1, bh - 3, 1)
    .rect(bx + 1, by + bh - 1, bw - 1, 1, 1);
  body.rect(bx, by, 1, bh - 1, 6);
  // metal shutter with its slot
  const sx = bx + 5;
  const sw = 11;
  const sh = 7;
  body
    .rect(sx, by, sw, sh, 6)
    .rect(sx + sw - 5, by + 2, 3, sh - 3, 5)
    .rect(sx, by + sh - 1, sw, 1, 5);
  // label with the face
  const lx = bx + 3;
  const ly = by + sh + 3;
  const lw = bw - 6;
  body.rect(lx, ly, lw, bh - sh - 5, 7);
  const ey = ly + 2;
  for (const x of [lx + 3, lx + lw - 5])
    body.rect(x, ey, 2, 4, 0).set(x, ey, 7);
  body.rect(lx + 1, ey + 5, 2, 1, 14).rect(lx + lw - 3, ey + 5, 2, 1, 14);
  body.art(lx + Math.floor(lw / 2) - 3, ey + 5, ["0....0", ".0000."]);
  return img.blit(body.outline());
}

