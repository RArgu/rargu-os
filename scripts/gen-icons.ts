// ---------- write everything ----------

function write(path: string, img: Img): void {
  const full = join(root, path);
  mkdirSync(dirname(full), { recursive: true });
  writeFileSync(full, img.png());
}

const sheet: [string, Img][] = [];

// the hosted apps' icons (the registry imports them); guide and settings only
// have small copies below
for (const id of ["writer", "paint", "tracker", "castlesiege"]) {
  const big = APPS32[id]();
  const small = big.half();
  write(`src/apps/${id}/icon.png`, big);
  write(`src/apps/${id}/icon-16.png`, small);
  sheet.push([id, big], [id + "-16", small]);
}
for (const [name, draw] of Object.entries(ICONS32)) {
  const big = draw();
  write(`system/usr/share/icons/${name}.png`, big);
  write(`system/usr/share/icons/${name}-16.png`, big.half());
  sheet.push([name, big], [name + "-16", big.half()]);
}
for (const [name, art] of Object.entries(UI16)) {
  const img = a16(art);
  write(`system/usr/share/icons/${name}.png`, img);
  sheet.push([name, img]);
}
// light versions for the compact status bar, which sits on the wallpaper
for (const name of ["sound-on", "sound-off"]) {
  const img = a16(UI16[name]);
  img.px = img.px.map((c) => (c === 0 ? 7 : c));
  write(`system/usr/share/icons/${name}-light.png`, img);
}
// small copies of app icons the shell uses by name
write("system/usr/share/icons/guide-16.png", APPS32.guide().half());
write("system/usr/share/icons/writer-16.png", APPS32.writer().half());
write("system/usr/share/icons/tab-system.png", APPS32.settings().half());

if (process.env.SHEET) {
  // contact sheet for reviewing the art: every image at 4x on gray and navy
  const cell = 52 * 4;
  const cols = 8;
  const rows = Math.ceil(sheet.length / cols);
  const out = new Img(cols * cell, rows * cell);
  sheet.forEach(([, img], i) => {
    const x = (i % cols) * cell;
    const y = Math.floor(i / cols) * cell;
    out.rect(x, y, cell, cell, i % 2 ? 6 : 1);
    out.blit(img.scale(4), x + 8, y + 8);
  });
  writeFileSync(process.env.SHEET, out.png());
  console.log(sheet.map(([n], i) => `${i}:${n}`).join(" "));
}
console.log(`icons: ${sheet.length} images written`);
