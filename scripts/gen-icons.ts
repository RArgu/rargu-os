/** A sheet of paper with a folded corner. */
function page(lines: C | null = "c"): Img {
  const p = layer().rect(7, 3, 18, 26, 7);
  for (let d = 0; d < 6; d++) {
    for (let e = 0; e < 6; e++) {
      if (e > d) p.set(19 + e, 3 + d, ".");
      else if (e === d || d === 5) p.set(19 + e, 3 + d, 6);
    }
  }
  p.rect(24, 9, 1, 20, 6).rect(8, 28, 17, 1, 6);
  if (lines !== null)
    for (const y of [11, 14, 17, 20, 23])
      p.rect(10, y, y === 23 ? 8 : 12, 1, lines);
  return p.outline();
}

function monitor(screen: C): Img {
  const m = layer();
  m.rect(4, 5, 24, 18, 6).rect(6, 7, 20, 14, screen);
  m.rect(4, 22, 24, 1, 5).rect(27, 5, 1, 18, 5);
  m.rect(13, 24, 6, 2, 5).rect(9, 26, 14, 2, 6);
  return m.outline();
}

