const T = 16; // transparent index

type C = string | number;
const idx = (c: C): number =>
  typeof c === "number" ? c : c === "." ? T : parseInt(c, 16);

class Img {
  px: Uint8Array;
  readonly w: number;
  readonly h: number;
  constructor(w: number, h: number) {
    this.w = w;
    this.h = h;
    this.px = new Uint8Array(w * h).fill(T);
  }
  get(x: number, y: number): number {
    return x < 0 || y < 0 || x >= this.w || y >= this.h
      ? T
      : this.px[y * this.w + x];
  }
  set(x: number, y: number, c: C): this {
    x = Math.round(x);
    y = Math.round(y);
    if (x >= 0 && y >= 0 && x < this.w && y < this.h)
      this.px[y * this.w + x] = idx(c);
    return this;
  }
  rect(x: number, y: number, w: number, h: number, c: C): this {
    for (let j = 0; j < h; j++)
      for (let i = 0; i < w; i++) this.set(x + i, y + j, c);
    return this;
  }
  box(x: number, y: number, w: number, h: number, c: C): this {
    this.rect(x, y, w, 1, c).rect(x, y + h - 1, w, 1, c);
    return this.rect(x, y, 1, h, c).rect(x + w - 1, y, 1, h, c);
  }
  line(x0: number, y0: number, x1: number, y1: number, c: C, t = 1): this {
    const dx = Math.abs(x1 - x0);
    const dy = Math.abs(y1 - y0);
    const sx = x0 < x1 ? 1 : -1;
    const sy = y0 < y1 ? 1 : -1;
    let err = dx - dy;
    for (;;) {
      this.rect(x0, y0, t, t, c);
      if (x0 === x1 && y0 === y1) break;
      const e2 = 2 * err;
      if (e2 > -dy) {
        err -= dy;
        x0 += sx;
      }
      if (e2 < dx) {
        err += dx;
        y0 += sy;
      }
    }
    return this;
  }
  /** Filled ellipse; centers may be .5 for even sizes. */
  disc(cx: number, cy: number, rx: number, ry: number, c: C): this {
    for (let y = Math.floor(cy - ry); y <= Math.ceil(cy + ry); y++) {
      for (let x = Math.floor(cx - rx); x <= Math.ceil(cx + rx); x++) {
        const nx = (x - cx) / (rx + 0.3);
        const ny = (y - cy) / (ry + 0.3);
        if (nx * nx + ny * ny <= 1) this.set(x, y, c);
      }
    }
    return this;
  }
  tri(
    x0: number,
    y0: number,
    x1: number,
    y1: number,
    x2: number,
    y2: number,
    c: C,
  ): this {
    const minX = Math.min(x0, x1, x2);
    const maxX = Math.max(x0, x1, x2);
    const minY = Math.min(y0, y1, y2);
    const maxY = Math.max(y0, y1, y2);
    const edge = (
      ax: number,
      ay: number,
      bx: number,
      by: number,
      px: number,
      py: number,
    ): number => (bx - ax) * (py - ay) - (by - ay) * (px - ax);
    for (let y = minY; y <= maxY; y++) {
      for (let x = minX; x <= maxX; x++) {
        const a = edge(x0, y0, x1, y1, x, y);
        const b = edge(x1, y1, x2, y2, x, y);
        const d = edge(x2, y2, x0, y0, x, y);
        if ((a >= 0 && b >= 0 && d >= 0) || (a <= 0 && b <= 0 && d <= 0))
          this.set(x, y, c);
      }
    }
    return this;
  }
  /** ASCII art: hex digits are palette slots, "." is skipped. */
  art(x: number, y: number, rows: string[]): this {
    rows.forEach((row, j) => {
      [...row].forEach((ch, i) => {
        if (ch !== ".") this.set(x + i, y + j, ch);
      });
    });
    return this;
  }
  /** Adds a 1px outline around everything opaque. */
  outline(c: C = 0): this {
    const src = this.px.slice();
    const at = (x: number, y: number): number =>
      x < 0 || y < 0 || x >= this.w || y >= this.h ? T : src[y * this.w + x];
    for (let y = 0; y < this.h; y++) {
      for (let x = 0; x < this.w; x++) {
        if (at(x, y) !== T) continue;
        if (
          at(x - 1, y) !== T ||
          at(x + 1, y) !== T ||
          at(x, y - 1) !== T ||
          at(x, y + 1) !== T
        ) {
          this.px[y * this.w + x] = idx(c);
        }
      }
    }
    return this;
  }
  blit(src: Img, ox = 0, oy = 0): this {
    for (let y = 0; y < src.h; y++) {
      for (let x = 0; x < src.w; x++) {
        const c = src.px[y * src.w + x];
        if (c !== T) this.set(ox + x, oy + y, c);
      }
    }
    return this;
  }
  /** 2x2 dither of two colors over a rectangle; `mix` 0..4 picks how much of b. */
  dither(
    x: number,
    y: number,
    w: number,
    h: number,
    a: C,
    b: C,
    mix = 2,
  ): this {
    const order = [0, 2, 3, 1];
    for (let j = 0; j < h; j++) {
      for (let i = 0; i < w; i++) {
        const t = order[(((y + j) & 1) << 1) | ((x + i) & 1)];
        this.set(x + i, y + j, t < mix ? b : a);
      }
    }
    return this;
  }
  /** Halves the size: each 2x2 block becomes its most common color. */
  half(): Img {
    const out = new Img(this.w / 2, this.h / 2);
    for (let y = 0; y < out.h; y++) {
      for (let x = 0; x < out.w; x++) {
        const cs = [
          this.get(2 * x, 2 * y),
          this.get(2 * x + 1, 2 * y),
          this.get(2 * x, 2 * y + 1),
          this.get(2 * x + 1, 2 * y + 1),
        ];
        const solid = cs.filter((c) => c !== T);
        if (solid.length < 2) continue;
        const count = new Map<number, number>();
        for (const c of solid) count.set(c, (count.get(c) ?? 0) + 1);
        // prefer fills over the outline when tied, so shapes keep their color
        const best = [...count.entries()].sort(
          (a, b) => b[1] - a[1] || (a[0] === 0 ? 1 : -1),
        )[0][0];
        out.set(x, y, best);
      }
    }
    return out.reoutline();
  }
  /** After downscaling, make sure the silhouette still has a dark edge. */
  private reoutline(): this {
    const src = this.px.slice();
    const at = (x: number, y: number): number =>
      x < 0 || y < 0 || x >= this.w || y >= this.h ? T : src[y * this.w + x];
    for (let y = 0; y < this.h; y++) {
      for (let x = 0; x < this.w; x++) {
        if (at(x, y) === T) continue;
        const edge =
          at(x - 1, y) === T ||
          at(x + 1, y) === T ||
          at(x, y - 1) === T ||
          at(x, y + 1) === T;
        if (edge) this.px[y * this.w + x] = 0;
      }
    }
    return this;
  }
  scale(n: number): Img {
    const out = new Img(this.w * n, this.h * n);
    for (let y = 0; y < out.h; y++) {
      for (let x = 0; x < out.w; x++)
        out.px[y * out.w + x] = this.get(Math.floor(x / n), Math.floor(y / n));
    }
    return out;
  }
  png(palette: string[] = PALETTE): Buffer {
    const raw = Buffer.alloc((this.w + 1) * this.h);
    for (let y = 0; y < this.h; y++) {
      raw[y * (this.w + 1)] = 0;
      for (let x = 0; x < this.w; x++)
        raw[y * (this.w + 1) + 1 + x] = this.px[y * this.w + x];
    }
    const chunk = (type: string, data: Buffer): Buffer => {
      const len = Buffer.alloc(4);
      len.writeUInt32BE(data.length);
      const body = Buffer.concat([Buffer.from(type, "ascii"), data]);
      const crc = Buffer.alloc(4);
      crc.writeUInt32BE(crc32(body) >>> 0);
      return Buffer.concat([len, body, crc]);
    };
    const ihdr = Buffer.alloc(13);
    ihdr.writeUInt32BE(this.w, 0);
    ihdr.writeUInt32BE(this.h, 4);
    ihdr.set([8, 3, 0, 0, 0], 8);
    const plte = Buffer.alloc(17 * 3);
    palette.forEach((hex, i) => {
      plte.set(
        [
          parseInt(hex.slice(1, 3), 16),
          parseInt(hex.slice(3, 5), 16),
          parseInt(hex.slice(5, 7), 16),
        ],
        i * 3,
      );
    });
    const trns = Buffer.alloc(17, 255);
    trns[T] = 0;
    return Buffer.concat([
      Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
      chunk("IHDR", ihdr),
      chunk("PLTE", plte),
      chunk("tRNS", trns),
      chunk("IDAT", deflateSync(raw, { level: 9 })),
      chunk("IEND", Buffer.alloc(0)),
    ]);
  }
}

const layer = (w = 32, h = 32): Img => new Img(w, h);

/** A 16x16 icon from 16 rows of ASCII art. */
function a16(rows: string): Img {
  const lines = rows.trim().split(/\s+/);
  if (lines.length !== 16 || lines.some((l) => l.length !== 16)) {
    throw new Error("16x16 art must be 16 rows of 16 characters:\n" + rows);
  }
  return new Img(16, 16).art(0, 0, lines);
}

